def glyph_bitmap(ch):
    """(GH, GW) uint8 0/255 bitmap of a glyph"""
    rows = GLYPHS[ch].split()
    assert len(rows) in (CAP, GH) and all(len(r) == GW for r in rows), (ch, rows)
    rows = rows + ["." * GW] * (GH - len(rows))
    return np.array([[255 if c == "#" else 0 for c in r] for r in rows], np.uint8)
